"""Time the bootstrap stage by stage, NumPy against C++, and write ``results/benchmark.md``.

Run it with ``uv run python bench/bench_risk.py`` (about a minute; most of it is NumPy at
100,000 paths).

Both backends run :func:`pairslab.risk.bootstrap_risk` on the same synthetic return series
(2,262 days, the length of the real out-of-sample sample, Student-t with 3 degrees of
freedom), with the same seed, so they simulate the *same* histories. Each configuration is run
``--repeats`` times and the median time of every stage is reported (the median ignores a
single slow run caused by something else on the machine). One thread for both backends.
"""

from __future__ import annotations

import argparse
import platform
import statistics
import subprocess
import sys
from collections.abc import Sequence
from datetime import date
from pathlib import Path

import numpy as np

from pairslab.risk import CHUNK_SIZE, DEFAULT_SEED, STAGES, BootstrapResult, bootstrap_risk

N_DAYS = 2262  # length of the real stitched out-of-sample series
MEAN_BLOCK = 1.0  # the Politis-White choice for the OLS variant
DEFAULT_PATHS = (10_000, 100_000)
STAGE_LABELS = {
    "indices": "index generation",
    "gather": "gather (r[idx])",
    "tail_1d": "1-day VaR/CVaR",
    "tail_10d": "10-day VaR/CVaR",
    "drawdown": "drawdown + final return",
    "sharpe": "Sharpe",
    "total": "**total (end to end)**",
}


def synthetic_returns(n_days: int = N_DAYS, seed: int = 0) -> np.ndarray:
    """Fat-tailed daily returns with a 0.4% scale and a small positive drift."""
    return np.random.default_rng(seed).standard_t(3, n_days) * 0.004 + 0.0002


def time_backend(
    returns: np.ndarray, n_paths: int, backend: str, repeats: int
) -> tuple[dict[str, float], BootstrapResult]:
    """Run the bootstrap ``repeats`` times; return the median seconds per stage and the last run.

    Args:
        returns: Daily returns to resample.
        n_paths: Histories per run.
        backend: ``"numpy"`` or ``"cpp"``.
        repeats: Number of timed runs.

    Returns:
        ``({stage: median seconds}, last result)``; stages are those of
        :data:`pairslab.risk.STAGES` plus ``total``.

    """
    runs = []
    result = None
    for _ in range(repeats):
        result = bootstrap_risk(
            returns, n_paths=n_paths, mean_block=MEAN_BLOCK, seed=DEFAULT_SEED, backend=backend
        )
        runs.append(result.timings)
    assert result is not None
    medians = {stage: statistics.median(t[stage] for t in runs) for stage in (*STAGES, "total")}
    return medians, result


def max_abs_difference(a: BootstrapResult, b: BootstrapResult) -> float:
    """Largest absolute difference between the two backends over every statistic and history.

    Absolute, not relative: every statistic is a fraction or ratio of order 0.001-1, and a
    relative difference explodes for a final return that happens to be close to zero.
    """
    return max(float(np.max(np.abs(b.stats[k] - ref))) for k, ref in a.stats.items())


def machine_description() -> str:
    """CPU (where the OS tells us), OS and Python/NumPy versions."""
    cpu = platform.processor() or platform.machine()
    if sys.platform == "darwin":
        try:
            cpu = subprocess.run(
                ["sysctl", "-n", "machdep.cpu.brand_string"],
                capture_output=True,
                text=True,
                check=True,
            ).stdout.strip()
        except (OSError, subprocess.CalledProcessError):
            pass
    return (
        f"{cpu}, {platform.system()} {platform.release()}, Python {platform.python_version()}, "
        f"NumPy {np.__version__}"
    )


def format_markdown(
    rows: Sequence[tuple[int, dict[str, float], dict[str, float], float]], repeats: int
) -> str:
    """Render the benchmark as Markdown.

    Args:
        rows: ``(n_paths, numpy medians, cpp medians, max absolute difference)`` per size.
        repeats: Runs per configuration (for the description).

    Returns:
        The Markdown text.

    """
    lines = [
        "# Bootstrap benchmark: NumPy vs C++",
        "",
        f"Generated by `bench/bench_risk.py` on {date.today().isoformat()}.",
        "",
        f"- Machine: {machine_description()}",
        f"- Workload: stationary bootstrap of {N_DAYS:,} daily returns (Student-t, 3 df), mean "
        f"block {MEAN_BLOCK:g}, seed {DEFAULT_SEED}, chunks of {CHUNK_SIZE:,} histories",
        f"- Each cell is the median of {repeats} runs, in seconds; one thread for both backends",
        "- Both backends simulate the same histories (C++ reproduces NumPy's PCG64 stream), so "
        "the times measure the same work",
        "",
    ]
    for n_paths, ref, cpp, diff in rows:
        lines += [
            f"## {n_paths:,} paths ({n_paths * N_DAYS / 1e6:,.1f} million simulated days)",
            "",
            "| stage | NumPy (s) | C++ (s) | speedup |",
            "|---|---:|---:|---:|",
        ]
        for stage, label in STAGE_LABELS.items():
            speedup = ref[stage] / cpp[stage] if cpp[stage] > 0 else float("inf")
            lines.append(f"| {label} | {ref[stage]:.3f} | {cpp[stage]:.3f} | {speedup:.1f}x |")
        lines += [
            "",
            f"Throughput: NumPy {n_paths / ref['total']:,.0f} paths/s, "
            f"C++ {n_paths / cpp['total']:,.0f} paths/s. Largest absolute difference between "
            f"the two backends over all statistics and histories: {diff:.1e} (VaR, CVaR, "
            "drawdown and returns are fractions of equity, so this is rounding).",
            "",
        ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    """Command line: run the benchmark and write the Markdown report."""
    parser = argparse.ArgumentParser(description="NumPy vs C++ bootstrap benchmark")
    parser.add_argument("--paths", type=int, nargs="+", default=list(DEFAULT_PATHS))
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--out", default="results/benchmark.md")
    args = parser.parse_args(argv)

    returns = synthetic_returns()
    bootstrap_risk(returns, n_paths=100, mean_block=MEAN_BLOCK, backend="cpp")  # warm up
    rows = []
    for n_paths in args.paths:
        ref, ref_result = time_backend(returns, n_paths, "numpy", args.repeats)
        cpp, cpp_result = time_backend(returns, n_paths, "cpp", args.repeats)
        diff = max_abs_difference(ref_result, cpp_result)
        rows.append((n_paths, ref, cpp, diff))
        print(f"{n_paths:>7,} paths: NumPy {ref['total']:.2f} s, C++ {cpp['total']:.2f} s, "
              f"speedup {ref['total'] / cpp['total']:.1f}x, max abs diff {diff:.1e}")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(format_markdown(rows, args.repeats))
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
